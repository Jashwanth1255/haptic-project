"""Write PLACEHOLDER stimuli for study/rating_instrument.html.

    python make_study_stimuli.py

Writes study/images/placeholder_*.png (generated noise, not fabric) and
study/stimuli.js holding STIMULI (the images to rate) and PATTERNS (vibration
patterns per fabric and scheme, from synthetic signals).

**None of this may be used with participants.** It lets the page be built and
tested. Before the pilot, STIMULI must list the real fabric images, including the
Cluster surface scans and product photographs, and PATTERNS must come from real
descriptors. The page shows a banner while `PLACEHOLDER` is true.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from PIL import Image

from haptic import descriptor as D
from haptic import render as R
from haptic import signals as G

HERE = Path(__file__).parent
STUDY = HERE / "study"
N_IMAGES = 8
FABRICS = ("satin-slick", "corduroy-wide", "denim-heavy", "felt-matte")
VELOCITY_MM_S = 40.0


def images() -> list[dict]:
    rng = np.random.default_rng(0)
    folder = STUDY / "images"
    folder.mkdir(parents=True, exist_ok=True)
    out = []
    for i in range(N_IMAGES):
        scale = 2 + 6 * i
        noise = rng.random((256 // scale + 1, 256 // scale + 1))
        big = np.kron(noise, np.ones((scale, scale)))[:256, :256]
        name = f"placeholder_{i:02d}.png"
        Image.fromarray((big * 255).astype(np.uint8)).convert("RGB").save(folder / name)
        out.append({"id": name, "src": f"images/{name}"})
    return out


def patterns() -> dict:
    bank = {m.name: m for m in G.FABRIC_BANK}
    recs = {f: G.synthesize(bank[f], VELOCITY_MM_S, seed=0) for f in FABRICS}
    descs = {f: D.extract(x, G.FS_HZ) for f, x in recs.items()}
    cfg = R.RenderConfig(intensity_ref=R.intensity_reference(descs.values()))
    return {f: {s: list(p.durations) for s, p in
                R.encode_all(descs[f], cfg, R.signal_envelope(recs[f], G.FS_HZ)).items()}
            for f in FABRICS}


def main() -> int:
    stim, pats = images(), patterns()
    (STUDY / "stimuli.js").write_text(
        "// GENERATED by make_study_stimuli.py. PLACEHOLDER: noise images and synthetic\n"
        "// vibration patterns. Replace both before any participant sees the page.\n"
        "const PLACEHOLDER = true;\n"
        f"const STIMULI = {json.dumps(stim, indent=1)};\n"
        f"const PATTERNS = {json.dumps(pats)};\n", encoding="utf-8")
    print(f"wrote {len(stim)} placeholder images and patterns for {len(pats)} fabrics")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
